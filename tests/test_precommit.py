VALIDATE = pc.Hook(
    "solohost-validate",
    args=("validate",),
    name="validate things",
    files=r"^things/.*\.md$",
)
INDEX = pc.Hook(
    "solohost-index",
    stage="post-merge",
    args=("index", "."),
    always_run=True,
    pass_filenames=False,
)
HOOKS = (VALIDATE, INDEX)

# A stand-in for ``pre-commit install --hook-type <stage>``: writes the script
# pre-commit would, marker included, into the repo's hooks directory.
FAKE = """\
import sys
from pathlib import Path
stage = sys.argv[sys.argv.index("--hook-type") + 1]
hooks = Path(".git") / "hooks"
hooks.mkdir(exist_ok=True)
(hooks / stage).write_text("#!/bin/sh\\n# generated by pre-commit\\n")
"""


@pytest.fixture
def fake(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> tuple[str, ...]:
    # A global core.hooksPath on the developer's machine would otherwise leak
    # into every verdict below.
    monkeypatch.setenv("GIT_CONFIG_GLOBAL", os.devnull)
    monkeypatch.setenv("GIT_CONFIG_SYSTEM", os.devnull)
    script = tmp_path / "fake-pre-commit.py"
    script.write_text(FAKE, encoding="utf-8")
    return (sys.executable, str(script))


def _report(
    host: Host, root: Path, mode: Mode, previous: Mode | None = None
) -> inst.InstallReport:
    return inst.InstallReport(host, mode, root, previous=previous)


def test_hook_entry_is_derived_from_the_invocation() -> None:
    assert VALIDATE.entry("solohost") == "solohost validate"
    assert INDEX.entry("uv run solohost") == "uv run solohost index ."
    text = INDEX.render("solohost")
    assert "stages: [post-merge]" in text
    assert "always_run: true" in text
    assert "pass_filenames: false" in text
    assert "name: 'solohost-index'" in text
    plain = VALIDATE.render("solohost")
    # Declared even at the default stage: an omitted key means every stage.
    assert "stages: [pre-commit]" in plain and "always_run" not in plain
    # pre-commit's default is to pass filenames, so a file-scoped hook says
    # nothing about it: an omitted key is the same as `true`.
    assert "pass_filenames" not in plain
    assert "files: '^things/.*\\.md$'" in plain


def test_free_text_fields_are_quoted_for_yaml() -> None:
    # A regex or a name may carry `: ` or ` #`, which an unquoted scalar
    # would read as a mapping or a comment; a `'` inside is doubled.
    hook = pc.Hook("h", name="check: it's #1", files=r"^docs/(a|b): .*#.*$")
    text = hook.render("solohost")
    assert "name: 'check: it''s #1'" in text
    assert "files: '^docs/(a|b): .*#.*$'" in text
    parsed = yaml.safe_load("repos:\n  - repo: local\n    hooks:\n" + text)
    (entry,) = parsed["repos"][0]["hooks"]
    assert entry["name"] == "check: it's #1"
    assert entry["files"] == r"^docs/(a|b): .*#.*$"


def test_precommit_command_follows_the_mode() -> None:
    assert pc.precommit_command(SOLO, "global") == ("pre-commit",)
    assert pc.precommit_command(SOLO, "local") == ("uv", "run", "pre-commit")
    custom = dataclasses.replace(SOLO, local_prefix="poetry run")
