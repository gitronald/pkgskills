def test_checks_never_gate_and_name_the_fix(
    box: Sandbox, fake: tuple[str, ...]
) -> None:
    rows = pc.checks(SOLO, box.repo, "local", HOOKS)
    assert [row.label for row in rows] == [
        "hook solohost-validate",
        "hook solohost-index",
    ]
    assert {row.status for row in rows} == {"missing"}
    assert not any(row.gates for row in rows)
    assert "run `uv run solohost install --local`" in rows[0].note

    pc.wire(_report(SOLO, box.repo, "local"), HOOKS, activate=False, precommit=fake)
    rows = pc.checks(SOLO, box.repo, None, HOOKS)
    assert {row.status for row in rows} == {"unregistered"}
    # No mode given and nothing installed: the host's default names the fix.
    assert "`pre-commit install --hook-type pre-commit`" in rows[0].note
    assert "`pre-commit install --hook-type post-merge`" in rows[1].note
    rows = pc.checks(SOLO, box.repo, "local", HOOKS, precommit=("pc",))
    assert "`pc install --hook-type pre-commit`" in rows[0].note

    pc.wire(_report(SOLO, box.repo, "local"), HOOKS, precommit=fake)
    rows = pc.checks(SOLO, box.repo, "local", HOOKS)
    assert {row.status for row in rows} == {"active"}
    assert all(row.note == "" for row in rows)

    (box.repo / ".git").rename(box.repo / "not-git")
    rows = pc.checks(SOLO, box.repo, "local", HOOKS)
    assert {row.status for row in rows} == {"no_git_repo"}
    assert "no git repository" in rows[0].note


