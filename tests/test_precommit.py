def test_the_clone_is_consulted_once_per_call(
    box: Sandbox, fake: tuple[str, ...], monkeypatch: pytest.MonkeyPatch
) -> None:
    calls: list[list[str]] = []
    real = pc.run

    def counting(root: Path, argv: list[str], **kwargs: object):  # noqa: ANN202
        calls.append(list(argv))
        return real(root, argv, **kwargs)  # type: ignore[arg-type]

    monkeypatch.setattr(pc, "run", counting)
    stages = (VALIDATE, INDEX, pc.Hook("solohost-push", stage="pre-push"))
    pc.wire(_report(SOLO, box.repo, "local"), stages, precommit=fake)
    git = [argv for argv in calls if argv[0] == "git"]
    assert len(git) == 2  # rev-parse and config, not once per stage
    assert sum(argv[-2:-1] == ["--hook-type"] for argv in calls) == 3

    calls.clear()
    pc.checks(SOLO, box.repo, "local", stages)
    assert len([argv for argv in calls if argv[0] == "git"]) == 2

    calls.clear()
    assert pc.checks(SOLO, box.repo, "local", ()) == []
    assert calls == []


def test_wire_resyncs_the_entry_only_on_a_mode_switch(
    box: Sandbox, fake: tuple[str, ...]
) -> None:
    config = box.repo / ".pre-commit-config.yaml"
    pc.wire(_report(SOLO, box.repo, "local"), HOOKS, precommit=fake)
    local_text = config.read_text()

    # A same-mode refresh, and a first install with no prior mode: the
    # committed entry is deliberate repo content and stays.
    for previous in ("global", None):
        report = pc.wire(
            _report(SOLO, box.repo, "global", previous=previous),
            HOOKS,
            precommit=fake,
        )
        assert report.resynced == ()
        assert config.read_text() == local_text

    # A genuine switch rewrites the entries that name the other mode.
    report = pc.wire(
        _report(SOLO, box.repo, "global", previous="local"), HOOKS, precommit=fake
    )
    assert report.resynced == ("solohost-validate", "solohost-index")
    assert report.added == ()
    text = config.read_text()
    assert "entry: solohost validate\n" in text
    assert "entry: solohost index .\n" in text
    assert "uv run solohost" not in text

    # An entry that names neither invocation was customized; a switch leaves it.
    custom = text.replace("entry: solohost validate\n", "entry: ./bin/validate\n")
    config.write_text(custom, encoding="utf-8")
    report = pc.wire(
        _report(SOLO, box.repo, "local", previous="global"), HOOKS, precommit=fake
    )
    assert report.resynced == ("solohost-index",)
    assert "entry: ./bin/validate\n" in config.read_text()


