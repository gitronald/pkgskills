def test_wiring_from_after_install_end_to_end(
    box: Sandbox, fake: tuple[str, ...]
) -> None:
    seen: list[pc.HookReport] = []

    def after(report: inst.InstallReport) -> None:
        seen.append(pc.wire(report, HOOKS, precommit=fake))

    def extras(host: Host, root: Path, mode: Mode | None) -> list[ExtraCheck]:
        return pc.checks(host, root, mode, HOOKS, precommit=fake)

    host = dataclasses.replace(SOLO, after_install=after, extra_checks=extras)
    inst.install(host, box.repo, "local")
    assert seen[-1].created
    assert (
        "entry: uv run solohost validate"
        in (box.repo / ".pre-commit-config.yaml").read_text()
    )
    # A switch to global, seen through InstallReport.previous, resyncs.
    inst.install(host, box.repo, "global")
    assert seen[-1].resynced == ("solohost-validate", "solohost-index")
    assert (
        "entry: solohost validate" in (box.repo / ".pre-commit-config.yaml").read_text()
    )
    assert {row.status for row in pc.checks(EXAMPLE, box.repo, None, HOOKS)} == {
        "active"
    }
