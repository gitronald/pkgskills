@needs_git
def test_wire_reports_a_hookspath_block(box: Sandbox, fake: tuple[str, ...]) -> None:
    assert run(box.repo, ["git", "init", "-q"], capture_output=True).returncode == 0
    run(box.repo, ["git", "config", "core.hooksPath", "hooks"], capture_output=True)
    assert pc.hookspath_set(box.repo)
    report = pc.wire(_report(SOLO, box.repo, "local"), HOOKS, precommit=fake)
    assert set(report.activation.values()) == {"hookspath_blocked"}
    # The effective hooks dir is the configured one, so a script placed there
    # by other means still reads as registered.
    assert pc.hooks_dir(box.repo) == box.repo / "hooks"
    (box.repo / "hooks").mkdir()
    (box.repo / "hooks/pre-commit").write_text("# pre-commit\n")
    assert pc.registered(box.repo, "pre-commit")
    assert pc.hook_state(box.repo, VALIDATE) == "active"
    assert pc.hook_state(box.repo, INDEX) == "blocked"


def test_hooks_dir_falls_back_to_reading_git_itself(
    box: Sandbox, tmp_path: Path
) -> None:
    # A synthetic `.git` directory git refuses to answer for.
    assert pc.hooks_dir(box.repo) == box.repo / ".git/hooks"
    # A linked worktree's pointer file, relative and absolute.
    tree = tmp_path / "tree"
    tree.mkdir()
    (tree / ".git").write_text("gitdir: ../main/.git/worktrees/tree\n")
    assert pc.hooks_dir(tree) == tree / "../main/.git/worktrees/tree/hooks"
    (tree / ".git").write_text(f"gitdir: {tmp_path / 'main/.git'}\n")
    assert pc.hooks_dir(tree) == tmp_path / "main/.git/hooks"
    (tree / ".git").write_text("nonsense\n")
    assert pc.hooks_dir(tree) is None
    (tree / ".git").unlink()
    assert pc.hooks_dir(tree) is None


